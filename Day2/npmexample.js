//Here is what each command does:

//npm init -y - Creates a http://package.json file with default values.

//npm install express - Installs express as a production dependency.

//npm install lodash --save-dev - Installs lodash as a dev-only dependency.

//npm uninstall express - Removes express from the project.

//npm update - Updates all packages to latest allowed versions.

//npm list - Shows all installed packages.

//npm run start - Runs the "start" script defined in http://package.json.